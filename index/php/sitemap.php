<script>
const siteMenu = <?php echo json_encode($siteMenu, JSON_UNESCAPED_UNICODE); ?>;
let historyStack = [];

function renderMenu(level, key=null){
    const container = document.getElementById('menuContainer');
    container.innerHTML = '';
    const backBtn = document.getElementById('backBtn');

    if(level === 'categories'){
        backBtn.style.display = 'none';
        for(const cat in siteMenu){
            const div = document.createElement('div');
            const subcats = siteMenu[cat]['subcategories'] || {};
            const items = siteMenu[cat]['items'] || [];

            // cliquable si au moins un sous-élément ou item avec URL
            const hasClickableSub = Object.keys(subcats).some(sub => (subcats[sub]['items'] && subcats[sub]['items'].length > 0));
            const hasClickableItem = items.some(item => item.url && item.url.trim() !== '');
            const isClickable = hasClickableSub || hasClickableItem;

            div.className = isClickable ? 'feature-card' : 'feature-card-disabled';
            div.dataset.type = 'category';
            div.dataset.key = cat;
            div.textContent = cat;
            container.appendChild(div);
        }
    } else if(level === 'subcategories'){
        backBtn.style.display = 'inline-block';
        const subcats = siteMenu[key]['subcategories'] || {};
        for(const sub in subcats){
            const div = document.createElement('div');
            const items = subcats[sub]['items'] || [];

            // cliquable si au moins un item avec URL
            const isClickable = items.some(item => item.url && item.url.trim() !== '');

            div.className = isClickable ? 'feature-card' : 'feature-card-disabled';
            div.dataset.type = 'subcategory';
            div.dataset.key = sub;
            div.dataset.parent = key;
            div.textContent = sub;
            container.appendChild(div);
        }

        // items directs de la catégorie (toujours cliquables)
        const directItems = siteMenu[key]['items'] || [];
        directItems.forEach(item=>{
            const div = document.createElement('div');
            div.className = 'feature-card';
            div.dataset.type = 'item';
            div.dataset.url = item.url;
            div.textContent = item.label;
            container.appendChild(div);
        });
    } else if(level === 'items'){
        backBtn.style.display = 'inline-block';
        const cat = key.parent;
        const sub = key.key;
        const items = siteMenu[cat]['subcategories'][sub]['items'] || [];
        items.forEach(item=>{
            const div = document.createElement('div');
            const isClickable = item.url && item.url.trim() !== '';
            div.className = isClickable ? 'feature-card' : 'feature-card-disabled';
            div.dataset.type = 'item';
            if(isClickable) div.dataset.url = item.url;
            div.textContent = item.label;
            container.appendChild(div);
        });
    }
}

// Gestion du clic sur les boutons
document.getElementById('menuContainer').addEventListener('click', e=>{
    const target = e.target.closest('.feature-card');
    if(!target) return;
    if(target.classList.contains('feature-card-disabled')) return; // ignorer les non-cliquables

    const type = target.dataset.type;
    if(type === 'category'){
        historyStack.push({level:'categories'});
        renderMenu('subcategories', target.dataset.key);
        historyStack.push({level:'subcategories', key: target.dataset.key});
    } else if(type === 'subcategory'){
        renderMenu('items', {parent: target.dataset.parent, key: target.dataset.key});
        historyStack.push({level:'items', key: target.dataset.key, parent: target.dataset.parent});
    } else if(type === 'item'){
        window.open(target.dataset.url, '_blank');
    }
});

// Bouton retour
document.getElementById('backBtn').addEventListener('click', ()=>{
    historyStack.pop(); // retire l'état actuel
    const last = historyStack.pop(); // reprend l'état précédent
    if(!last){
        renderMenu('categories');
        historyStack = [];
    } else if(last.level === 'categories'){
        renderMenu('categories');
        historyStack = [];
    } else if(last.level === 'subcategories'){
        renderMenu('subcategories', last.key);
        historyStack.push(last);
    }
});

// initial
renderMenu('categories');
</script>
